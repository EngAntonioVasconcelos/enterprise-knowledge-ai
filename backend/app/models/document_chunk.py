import uuid
from datetime import datetime, timezone

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    ForeignKey,
    Integer,
    Text,
    UniqueConstraint,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


def _now() -> datetime:
    return datetime.now(timezone.utc)


class DocumentChunk(Base):
    """A searchable passage of one document version (Phase 6, RAG Core).

    content is exactly text[start_char:end_char] of the version's normalized
    text, so a citation can point at the passage. Readers are the readers of
    the document (migration b5d9e2a7c4f1). The full-text column content_tsv
    is generated by PostgreSQL and left out of the model on purpose
    (migrations/env.py ignores it).
    """

    __tablename__ = "document_chunks"

    __table_args__ = (
        UniqueConstraint(
            "version_id",
            "ordinal",
            name="uq_document_chunks_version_ordinal",
        ),
        CheckConstraint("ordinal >= 0", name="ck_document_chunks_ordinal"),
        CheckConstraint(
            "start_char >= 0 AND end_char > start_char",
            name="ck_document_chunks_span",
        ),
        CheckConstraint(
            "length(content) > 0 AND length(content) <= 8000",
            name="ck_document_chunks_content",
        ),
        CheckConstraint("token_estimate > 0", name="ck_document_chunks_tokens"),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    organization_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("organizations.id"), nullable=False, index=True
    )
    document_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("documents.id"), nullable=False, index=True
    )
    version_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("document_versions.id"), nullable=False
    )
    ordinal: Mapped[int] = mapped_column(Integer, nullable=False)
    heading: Mapped[str | None] = mapped_column(Text, nullable=True)
    content: Mapped[str] = mapped_column(Text, nullable=False)
    start_char: Mapped[int] = mapped_column(Integer, nullable=False)
    end_char: Mapped[int] = mapped_column(Integer, nullable=False)
    token_estimate: Mapped[int] = mapped_column(Integer, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=_now
    )
